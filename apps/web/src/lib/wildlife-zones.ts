export function projLonToSvgX(lon: number): number {
  return +(40 + ((lon - 72.65) / (80.9 - 72.65)) * 720).toFixed(1);
}

export function projLatToSvgY(lat: number): number {
  return +(30 + ((22.05 - lat) / (22.05 - 15.6)) * 540).toFixed(1);
}

